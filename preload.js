const { contextBridge, ipcRenderer } = require('electron');

const on = (channel) => (cb) => ipcRenderer.on(channel, (e, d) => cb(d));

contextBridge.exposeInMainWorld('butler', {
  config: () => ipcRenderer.invoke('config'),
  mint: () => ipcRenderer.invoke('mint'),
  voiceTurn: (payload) => ipcRenderer.invoke('voice-turn', payload),
  liveSession: (sdp) => ipcRenderer.invoke('live-session', sdp),
  liveDelegate: (text) => ipcRenderer.invoke('live-delegate', text),
  liveRecord: (exchange) => ipcRenderer.invoke('live-record', exchange),
  speak: (text) => ipcRenderer.invoke('speak', text),
  chats: () => ipcRenderer.invoke('chats'),
  chat: (id) => ipcRenderer.invoke('chat', id),
  newChat: () => ipcRenderer.invoke('new-chat'),
  instructions: () => ipcRenderer.invoke('instructions'),
  settings: () => ipcRenderer.invoke('settings'),
  saveSettings: (s) => ipcRenderer.invoke('settings-save', s),
  edgeVoices: () => ipcRenderer.invoke('edge-voices'),
  tool: (name, args) => ipcRenderer.invoke('tool', { name, args }),
  snapshot: () => ipcRenderer.invoke('snapshot'),
  answer: (id, answer) => ipcRenderer.invoke('answer', { id, answer }),
  backdrop: () => ipcRenderer.invoke('backdrop'),
  visible: (on) => ipcRenderer.send('visible', !!on),
  panelState: (open) => ipcRenderer.send('panel-state', !!open),
  speaking: (on) => ipcRenderer.send('speaking', !!on),
  hit: (over) => ipcRenderer.send('hit', !!over),
  captions: (action, mode) => ipcRenderer.send('captions', { action, mode }),
  captionAudio: (buf) => ipcRenderer.send('caption-audio', buf),
  wakeAudio: (buf) => ipcRenderer.send('wake-audio', buf),
  log: (m) => ipcRenderer.send('log', String(m)),
  onPtt: on('ptt'),
  onPanel: on('panel'),
  onWake: on('wake'),
  onSay: on('say'),
  onShow: on('show'),
  onChime: on('chime'),
  onAlert: on('alert'),
  onState: on('state'),
  onCaption: on('caption'),
  onAgentEvent: on('agent-event'),
  onComputerEvent: on('computer-event'),
  onEndConversation: on('end-conversation'),
  onDevState: on('dev-state'),
  onVoiceEvent: on('voice-event'),
});
